import { readFile, writeFile } from 'node:fs/promises';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const site = 'https://kahwee.github.io/sf-map-svg/';
const documents = [
  ['README.md', 'index.md', 'Overview'],
  ['docs/developer-guide.md', 'developer-guide.md', 'Developer guide'],
  ['docs/API.md', 'api-options.md', 'API options and lifecycle'],
  ['docs/EXAMPLES.md', 'examples.md', 'Worked examples'],
  ['docs/consumer-integration.md', 'consumer-integration.md', 'Consumer integration'],
  ['docs/migration-v3.md', 'migration-v3.md', 'Migration from removed APIs'],
  ['SOURCES.md', 'sources.md', 'Geographic sources'],
  ['CHANGELOG.md', 'changelog.md', 'Changelog'],
];

// Use the selected package's docs and emitted declarations, including in npm-backed builds.
export async function buildLlmDocs(packageRoot, { released = false } = {}) {
  const pkg = JSON.parse(await readFile(join(packageRoot, 'package.json'), 'utf8'));
  const label = `@kahwee/sf-map-svg ${pkg.version} · ${released ? 'npm package' : 'local working tree'}`;
  const repository = `https://github.com/kahwee/sf-map-svg/blob/${released ? `v${pkg.version}` : 'main'}/`;
  const files = new Map();
  const entries = [];
  for (const [source, target, title] of documents) {
    const markdown = await readFile(join(packageRoot, source), 'utf8').catch((error) => {
      // Older releases may not contain newly introduced guides. Never borrow main's docs.
      if (released && error.code === 'ENOENT') return null;
      throw error;
    });
    if (markdown === null) continue;
    const linked = markdown.replace(/\[([^\]]+)\]\(([^)]+)\)/g, (match, text, href) => {
      if (/^(?:[a-z][a-z\d+.-]*:|\/\/|#)/i.test(href)) return match;
      return `[${text}](${repository}${join(dirname(source), href)})`;
    });
    files.set(target, `<!-- Generated from ${source}; ${label}. -->\n\n${linked.trim()}\n`);
    entries.push({ target, title });
  }

  if (!files.has('developer-guide.md')) {
    files.set('developer-guide.md', files.get('consumer-integration.md') ?? files.get('index.md'));
  }
  const contracts = [];
  const seen = new Set();
  async function declaration(path) {
    const absolute = resolve(packageRoot, path);
    if (seen.has(absolute)) return;
    seen.add(absolute);
    const content = await readFile(absolute, 'utf8');
    contracts.push(`### ${path}\n\n\`\`\`ts\n${content.trim()}\n\`\`\``);
    for (const [, dependency] of content.matchAll(/(?:from\s*|import\s*)['"](\.[^'"]+)['"]/g)) {
      if (!dependency.endsWith('.js')) continue;
      await declaration(join(dirname(path), dependency.replace(/\.js$/, '.d.ts')));
    }
  }
  for (const entry of Object.values(pkg.exports)) {
    if (typeof entry === 'object' && entry.types) await declaration(entry.types);
  }
  const exportTable = Object.entries(pkg.exports)
    .filter(([, entry]) => typeof entry === 'object' && entry.types)
    .map(
      ([name, entry]) =>
        `| ${name === '.' ? pkg.name : pkg.name + name.slice(1)} | ${entry.types} |`,
    )
    .join('\n');
  const types = `# Published type contracts\n\n${label}. These declarations are generated by TypeScript. Use package export paths, not the internal filenames below. Imported relative contracts are included for context, not as additional public entry points.\n\n| Public import | Declaration |\n| --- | --- |\n${exportTable}\n\n${contracts.join('\n\n')}\n`;
  files.set('types.md', types);
  files.set('api.md', `${files.get('api-options.md') ?? '# API reference\n'}\n${types}`);
  files.set(
    'docs.md',
    files.get('developer-guide.md') ??
      files.get('consumer-integration.md') ??
      files.get('index.md'),
  );

  const intro = `# SF Map SVG\n\n> Offline San Francisco SVG maps with explicit geographic imports, no runtime dependencies, static rendering, and a browser controller.\n\n${label}. Node ${pkg.engines.node} for server rendering; browsers need a DOM and a JSON-capable bundler.\n\n${released ? 'These docs come from the selected npm package.' : 'These are working-tree docs. Unreleased changelog entries may describe APIs absent from npm; verify the installed version before copying them.'}\n\nUse renderMap(data, options) for SVG strings; createMap(data, options) returns a controller. Mount map.element and destroy it on unmount. Choose mode explicitly: createMap defaults to basemap. Geography is separate; staticMapData and fullMapData have different shapes.\n`;
  const index = `${intro}\n## Documentation\n\n${entries
    .filter(({ target }) => !['sources.md', 'changelog.md'].includes(target))
    .map(({ target, title }) => `- [${title}](${site}${target})`)
    .join(
      '\n',
    )}\n- [Exact TypeScript contracts](${site}types.md)\n- [Complete documentation](${site}llms-full.txt): Guides and declarations in one file.\n\n## Optional\n\n- [Geographic sources](${site}sources.md)\n- [Changelog](${site}changelog.md)\n`;
  files.set('llms.txt', index);
  files.set(
    'llms-full.txt',
    `${intro}\n${entries.map(({ target }) => files.get(target)).join('\n---\n\n')}\n---\n\n${types}`,
  );
  return files;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = fileURLToPath(new URL('../', import.meta.url));
  const files = await buildLlmDocs(root);
  for (const name of ['llms.txt', 'llms-full.txt']) {
    if (process.argv.includes('--check')) {
      const existing = await readFile(join(root, name), 'utf8').catch(() => null);
      if (existing !== files.get(name)) throw new Error(`${name} is stale. Run pnpm docs:llms.`);
    } else await writeFile(join(root, name), files.get(name));
  }
  console.log(
    `${process.argv.includes('--check') ? 'Checked' : 'Generated'} ${basename(root)} assistant-readable documentation.`,
  );
}
